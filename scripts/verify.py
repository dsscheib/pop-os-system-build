def strip_fences(text):
    out, fence_char, fence_len = [], None, 0
    for line in text.splitlines():
        if fence_char is None:
            m = FENCE_OPEN.match(line)
            if m and (m.group(1)[0] == '~' or '`' not in m.group(2)):
                fence_char, fence_len = m.group(1)[0], len(m.group(1))
                out.append('')
                continue
            out.append(line)
        else:
            if re.match(rf'^ {{0,3}}{re.escape(fence_char)}{{{fence_len},}}[ \t]*$', line):
                fence_char, fence_len = None, 0
            out.append('')
    return '\n'.join(out)


def prose(text):
    return INLINE_CODE.sub('', strip_fences(text))


def rel(path):
    return path.relative_to(root).as_posix()


def git(*args):
    try:
        r = subprocess.run(['git', '-C', str(root), *args], capture_output=True, text=True)
    except OSError:
        return ''
    return r.stdout.strip() if r.returncode == 0 else ''


def git_z(*args):
    try:
        r = subprocess.run(['git', '-C', str(root), *args], capture_output=True, text=True)
    except OSError:
        return None
    return [x for x in r.stdout.split('\0') if x] if r.returncode == 0 else None


def git_ignored():
    try:
        r = subprocess.run(['git', '-C', str(root), 'ls-files', '--others', '--ignored', '--exclude-standard',
                            '--directory', '-z'], capture_output=True, text=True)
    except OSError:
        return set()
    return set(filter(None, r.stdout.split('\0'))) if r.returncode == 0 else set()


def walk():
    ignored = git_ignored()
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        here = Path(dirpath)
        base = '' if here == root else rel(here) + '/'
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and base + d + '/' not in ignored
                       and not (here / d / '.git').exists()]
        found += [here / f for f in filenames if base + f not in ignored and (here / f).is_file()]
    return sorted(found)


def frontmatter(text):
    if not text.startswith('---\n') or '\n---\n' not in text[4:]:
        return {}
    fields = {}
    for line in text[4:text.index('\n---\n', 4)].splitlines():
        k, sep, v = line.partition(':')
        if sep:
            fields[k.strip()] = v.strip()
    return fields


def load_record():
    for path in (guidance_path, root / 'PACKAGE_MANIFEST.json'):
        if path.is_file():
            try:
                data = json.loads(path.read_text())
                if isinstance(data, dict):
                    return data, None
                return None, f'{rel(path)}: expected a JSON object'
            except ValueError as error:
                return None, f'{rel(path)}: not valid JSON ({error})'
    return None, '.guidance.json not found; restore installation metadata or reinstall with manage.py --install'


def recorded_exclusions(profile):
    row = EXCLUDED_ROW.search(profile.read_text()) if profile.is_file() else None
    paths = [t.strip('`').strip().removeprefix('./') for t in INLINE_CODE.findall(row.group(0))] if row else []
    return tuple(p for p in paths if '/' in p or '.' in p)


def excluded(path, exclusions):
    return any(path == e or (e.endswith('/') and path.startswith(e)) for e in exclusions)


def check_links(files, errors, uninstalled):
    skipped = 0
    for path in files:
        if path.suffix != '.md':
            continue
        for link in LINK.findall(prose(path.read_text(errors='replace'))):
            if '://' in link or link.startswith(('#', 'mailto:')):
                continue
            target = (path.parent / link.split('#')[0]).resolve()
            if target.is_relative_to(root) and not target.exists() and rel(target) in uninstalled:
                skipped += 1
            elif not target.is_relative_to(root) or not target.exists():
                errors.append(f'{rel(path)}: unresolved or escaping link {link}')
    return skipped


def check_shims(files, errors, claude=True):
    if not claude:
        return
    for path in files:
        if path.name == 'AGENTS.md':
            shim = path.with_name('CLAUDE.md')
            if not shim.is_file() or '@AGENTS.md' not in shim.read_text(errors='replace'):
                errors.append(f'{rel(path)}: needs a sibling CLAUDE.md containing @AGENTS.md for Claude Code')


def check_budget(errors):
    hint = 'move history to docs/RELEASE_NOTES.md or delete it'
    for path, limit in LINE_LIMITS.items():
        target = root / path
        if target.is_file():
            lines = len(target.read_text().splitlines())
            if lines > limit:
                errors.append(f'{path}: {lines} lines exceeds the {limit}-line budget; {hint}')
    profile = root / 'PROJECT_PROFILE.md'
    if profile.is_file():
        dated = [h for h in HEADING.findall(prose(profile.read_text())) if DATED.search(h)]
        if dated:
            errors.append(f'PROJECT_PROFILE.md: {len(dated)} dated heading(s), such as "{dated[0].strip()}"; '
                          f'this file holds stable facts only; {hint}')
    for path in POINTER_FILES:
        target = root / path
        if target.is_file():
            text = target.read_text()
            content = [line for line in text.splitlines() if line.strip()]
            if 'AGENTS.md' not in text or len(content) > POINTER_MAX_LINES:
                errors.append(f'{path}: tool instruction files may only point to AGENTS.md (at most {POINTER_MAX_LINES} lines)')


def check_skills(record, errors):
    installed = {e['path'] if isinstance(e, dict) else e for e in record.get('files', [])}
    tools = set((record.get('installed') or record).get('tools') or ())
    required_dirs = []
    if not tools or tools & {'codex', 'antigravity', 'copilot'}:
        required_dirs.append('.agents/skills')
    if not tools or 'claude' in tools:
        required_dirs.append('.claude/skills')
    # Copilot CLI also loads .claude/skills; validate generated wrappers there when present even on Copilot-only installs.
    extra_dirs = ['.claude/skills'] if ('copilot' in tools and '.claude/skills' not in required_dirs) else []
    proc_dir = root / 'docs' / 'procedures'
    expected_required, expected_extra = {}, {}
    if proc_dir.is_dir():
        for source in sorted(proc_dir.glob('*.md')):
            if installed and rel(source) not in installed:
                continue
            fields = frontmatter(source.read_text())
            name, desc = fields.get('name', ''), fields.get('description', '')
            if not name or not desc:
                continue
            body = (f'---\nname: {name}\ndescription: {json.dumps(desc)}\n---\n'
                    f'{SKILL_MARKER}{rel(source)}. Edit that file, then regenerate. -->\n\n'
                    f'# {name}\n\nRead `{rel(source)}` from the repository root and follow it exactly. '
                    'That file is the authoritative procedure; this wrapper only makes it discoverable as a skill.\n')
            for d in required_dirs:
                expected_required[f'{d}/{name}/SKILL.md'] = body
            for d in extra_dirs:
                expected_extra[f'{d}/{name}/SKILL.md'] = body
    for path, content in expected_required.items():
        target = root / path
        if target.is_file() and SKILL_MARKER not in target.read_text(errors='replace'):
            errors.append(f'{path} collides with a packaged skill name but was not generated by manage.py; rename or remove it')
        elif not target.is_file() or target.read_text() != content:
            errors.append(f'Stale or missing skill wrapper {path}; run manage.py --sync {root}')
    for path, content in expected_extra.items():
        target = root / path
        if target.is_file() and SKILL_MARKER not in target.read_text(errors='replace'):
            errors.append(f'{path} collides with a packaged skill name but was not generated by manage.py; rename or remove it')
        elif target.is_file() and target.read_text() != content:
            errors.append(f'Stale or missing skill wrapper {path}; run manage.py --sync {root}')
    expected_all = {**expected_required, **expected_extra}
    for d in required_dirs + extra_dirs:
        for p in (root / d).glob('*/SKILL.md') if (root / d).is_dir() else ():
            if rel(p) not in expected_all and SKILL_MARKER in p.read_text(errors='replace'):
                errors.append(f'Orphaned skill wrapper {rel(p)}; remove it or run manage.py --sync {root}')


def check_agents_tables(record, errors):
    blocks = record.get('agents_blocks')
    agents = root / 'AGENTS.md'
    if not isinstance(blocks, dict) or not blocks or not agents.is_file():
        return
    found = {}
    for match in GENERATED.finditer(agents.read_text(errors='replace')):
        found.setdefault(match.group(2), []).append(match.group(3))
    for name, expected in blocks.items():
        matches = found.get(name, [])
        if not matches:
            errors.append(f'AGENTS.md {name} table markers are missing; finish merging AGENTS.md '
                          f'(or restore the <!-- generated: {name} --> block), then run manage.py --sync {root}')
        elif len(matches) > 1:
            errors.append(f'AGENTS.md {name} table is duplicated; remove the duplicate block, '
                          f'then run manage.py --sync {root}')
        elif matches[0] != expected:
            errors.append(f'AGENTS.md {name} table does not match .guidance.json; '
                          f'run manage.py --sync {root}')


def valid_copilot_guardrail_cmd(cmd, cwd_val, expected_target, posix=True):
    if not isinstance(cmd, str) or not cmd.strip():
        return False
    try:
        tokens = shlex.split(cmd, posix=posix)
    except ValueError:
        return False
    if not posix:
        tokens = [t[1:-1] if len(t) >= 2 and t[0] == t[-1] and t[0] in ('"', "'") else t for t in tokens]
    if len(tokens) >= 3 and Path(tokens[0].replace('\\', '/')).name.lower() == 'env':
        tokens = tokens[1:]
    if len(tokens) < 2:
        return False
    if not re.fullmatch(r'(?:python(?:\d+(?:\.\d+)*)?|py)(?:\.exe)?', Path(tokens[0].replace('\\', '/')).name.lower()):
        return False
    if not all(re.fullmatch(r'-[bBEIOqsSuv]+', tok) for tok in tokens[1:-1]):
        return False
    script = tokens[-1]
    if not script or script.startswith('-'):
        return False
    if cwd_val is None:
        norm_cwd = '.'
    elif isinstance(cwd_val, str) and cwd_val.strip():
        norm_cwd = cwd_val.replace('\\', '/')
    else:
        return False
    resolved = ((root / norm_cwd) / script.replace('\\', '/')).resolve()
    return resolved == expected_target and resolved.is_file()


def guardrail_present(rel_path, text, token):
    if rel_path == '.claude/settings.json':
        try:
            data = json.loads(text)
        except ValueError:
            return False
        perms = data.get('permissions') if isinstance(data, dict) else None
        if not isinstance(perms, dict):
            return False
        ask = perms.get('ask') if isinstance(perms.get('ask'), list) else []
        deny = perms.get('deny') if isinstance(perms.get('deny'), list) else []
        allow = perms.get('allow') if isinstance(perms.get('allow'), list) else []
        return token in (ask + deny) and token not in allow
    if rel_path == '.codex/rules/guidance.rules':
        m = re.match(r'^pattern\s*=\s*(\[.*\])$', token.strip())
        if not m:
            return token in text
        try:
            want_pat = ast.literal_eval(m.group(1))
            tree = ast.parse(text)
        except (SyntaxError, ValueError):
            return False
        decisions = []
        for node in ast.walk(tree):
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == 'prefix_rule':
                kw = {k.arg: k.value for k in node.keywords if k.arg}
                if 'pattern' in kw and 'decision' in kw:
                    try:
                        pat = ast.literal_eval(kw['pattern'])
                        dec = ast.literal_eval(kw['decision'])
                    except ValueError:
                        continue
                    if pat == want_pat:
                        decisions.append(dec)
        return any(d in ('prompt', 'forbidden') for d in decisions) and 'allow' not in decisions
    if rel_path == '.github/hooks/guidance_guardrail.py':
        m = re.match(r'^\((\[.*\])\s*,$', token.strip())
        if not m:
            return token in text
        try:
            want_pat = ast.literal_eval(m.group(1))
            tree = ast.parse(text)
        except (SyntaxError, ValueError):
            return False
        top_assigns, decide_fn = {}, None
        for stmt in tree.body:
            if isinstance(stmt, ast.Assign):
                for t in stmt.targets:
                    if isinstance(t, ast.Name):
                        top_assigns[t.id] = stmt.value
            elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name) and stmt.value is not None:
                top_assigns[stmt.target.id] = stmt.value
            elif isinstance(stmt, ast.FunctionDef) and stmt.name == 'decide':
                decide_fn = stmt
        if decide_fn is None:
            return False
        gh_tables = []
        for node in ast.walk(decide_fn):
            if (isinstance(node, ast.Tuple) and len(node.elts) == 2
                    and isinstance(node.elts[0], ast.Constant) and node.elts[0].value == 'gh'
                    and isinstance(node.elts[1], ast.Name)):
                gh_tables.append(node.elts[1].id)
        for name in gh_tables:
            val = top_assigns.get(name)
            if isinstance(val, (ast.List, ast.Tuple)):
                for elt in val.elts:
                    if isinstance(elt, (ast.Tuple, ast.List)) and elt.elts:
                        try:
                            if ast.literal_eval(elt.elts[0]) == want_pat:
                                return True
                        except ValueError:
                            continue
        return False
    return token in text


def check_guardrails(record, errors):
    checks = record.get('guardrail_checks')
    if checks is None:
        meta = record.get('installed') or record
        modules = set(meta.get('modules') or ())
        if 'enterprise' not in modules:
            return
        tools = set(meta.get('tools') or ())
        fallback = [
            ('claude', 'merge a pull request', '.claude/settings.json', 'Bash(gh pr merge:*)'),
            ('claude', 'publish a release', '.claude/settings.json', 'Bash(gh release create:*)'),
            ('codex', 'merge a pull request', '.codex/rules/guidance.rules', 'pattern = ["gh", "pr", "merge"]'),
            ('codex', 'publish a release', '.codex/rules/guidance.rules', 'pattern = ["gh", "release", "create"]'),
            ('copilot', 'merge a pull request', '.github/hooks/guidance_guardrail.py', "(['pr', 'merge'],"),
            ('copilot', 'publish a release', '.github/hooks/guidance_guardrail.py', "(['release', 'create'],"),
        ]
        checks = [{'action': action, 'path': path, 'token': token}
                  for tool, action, path, token in fallback if not tools or tool in tools]
    for rule in checks:
        target = root / rule['path']
        if not target.is_file() or not guardrail_present(rule['path'], target.read_text(errors='replace'), rule['token']):
            errors.append(f"{rule['path']} lacks the enterprise guardrail that asks before you {rule['action']}; restore it from the package")
    if any(r['path'] == '.github/hooks/guidance_guardrail.py' for r in checks):
        hook_cfg = root / '.github' / 'hooks' / 'guidance.json'
        if not hook_cfg.is_file():
            errors.append('.github/hooks/guidance.json is missing for the Copilot preToolUse enterprise guardrail; restore it from the package')
        else:
            try:
                data = json.loads(hook_cfg.read_text())
            except ValueError:
                errors.append('.github/hooks/guidance.json is not valid JSON; restore it from the package')
            else:
                pre = (data.get('hooks') or {}).get('preToolUse') if isinstance(data, dict) else None
                expected_target = (root / '.github' / 'hooks' / 'guidance_guardrail.py').resolve()

                def valid_hook_entry(item):
                    if not isinstance(item, dict) or item.get('type', 'command') != 'command':
                        return False
                    keys = [k for k in ('bash', 'powershell') if k in item and item[k] is not None]
                    if not keys:
                        return False
                    if 'matcher' in item and item['matcher'] is not None:
                        matcher = item['matcher']
                        if not isinstance(matcher, str) or not matcher.strip():
                            return False
                        try:
                            pat = re.compile(matcher, re.I)
                        except re.error:
                            return False
                        if not all(pat.search(k) for k in keys):
                            return False
                    return all(
                        valid_copilot_guardrail_cmd(item[k], item.get('cwd'), expected_target, posix=(k == 'bash'))
                        for k in keys
                    )

                registered = isinstance(pre, list) and any(valid_hook_entry(item) for item in pre)
                if not registered:
                    errors.append('.github/hooks/guidance.json does not register guidance_guardrail.py under hooks.preToolUse; restore it from the package')


def enterprise_notes():
    notes = []
    doc = root / 'docs' / 'ENTERPRISE.md'
    row = next((l for l in doc.read_text().splitlines() if l.startswith('| Ticket ID pattern')), '') if doc.is_file() else ''
    pattern = INLINE_CODE.findall(row)
    if pattern:
        try:
            ticket = re.compile(pattern[0].strip('`'))
        except re.error:
            notes.append(f'Enterprise: the ticket ID pattern {pattern[0]} is not a valid regular expression')
            ticket = None
        commits = [c for c in git('log', '-20', '--format=%H%x00%B%x01').split('\x01') if c.strip()]
        missing = [c.strip().split('\x00')[0][:7] for c in commits if ticket and not ticket.search(c.split('\x00', 1)[-1])]
        if ticket and commits:
            notes.append(f'Enterprise: {len(missing)} of the last {len(commits)} commits lack a ticket ID'
                         + (f" ({', '.join(missing[:5])})" if missing else ''))
    else:
        notes.append('Enterprise: no ticket ID pattern is set in docs/ENTERPRISE.md, so traceability is not reported')
    if not any((root / p).is_file() for p in ('CODEOWNERS', '.github/CODEOWNERS', 'docs/CODEOWNERS')):
        notes.append('Enterprise: no CODEOWNERS file; approvals rely on the hosting service settings alone')
    workflows = list((root / '.github' / 'workflows').glob('*.y*ml')) if (root / '.github' / 'workflows').is_dir() else []
    if not any(re.search(r'(?:scripts/verify|check_package)\.py\s+--verify', w.read_text(errors='replace')) for w in workflows):
        notes.append('Enterprise: no CI workflow runs scripts/verify.py --verify, so there is no CI verification receipt')
    return notes


def gate_timeout(gate):
    m = GATE_TIMEOUT.search(gate)
    if not m:
        return None
    return int(m.group(1)) * {'s': 1, 'm': 60, 'h': 3600}[(m.group(2) or 's').lower()[0]]


def gate_labels(gate):
    cleaned = GATE_TIMEOUT.sub('', gate.lower()).strip(' ()')
    if not cleaned:
        return set()
    if cleaned in UNGATED_LABELS:
        return {cleaned}
    masked = re.sub(r'\bn/a\b', 'n__a', cleaned)
    return {'n/a' if p == 'n__a' else p for part in re.split(r'[/,;+&]|\band\b', masked) if (p := part.strip(' ()'))}


def split_table_row(line):
    s = line.strip()
    if s.startswith('|'):
        s = s[1:]
    if s.endswith('|') and not s.endswith('\\|'):
        s = s[:-1]
    return [re.sub(r'\\\|', '|', c).strip() for c in re.split(r'(?<!\\)\|', s)]


def inventory_gates(phase):
    profile = root / 'PROJECT_PROFILE.md'
    if not profile.is_file():
        return [], 'PROJECT_PROFILE.md not found'
    lines = strip_fences(profile.read_text()).splitlines()
    try:
        start = next(i for i, l in enumerate(lines) if re.match(r'^ {0,3}##[ \t]+command inventory[ \t]*$', l, re.I))
    except StopIteration:
        return [], 'no "## Command inventory" section in PROJECT_PROFILE.md'
    header, gates, bad_gates, bad_commands = None, [], [], []
    known = GATE_PHASES['release'] | UNGATED_LABELS
    for line in lines[start + 1:]:
        if re.match(r'^ {0,3}## ', line):
            break
        if not re.match(r'^ {0,3}\|', line):
            if header is not None:
                break
            continue
        cells = split_table_row(line)
        if header is None:
            header = [c.lower() for c in cells]
            continue
        if set(''.join(cells)) <= set('-: '):
            continue
        row = dict(zip(header, cells))
        gate = row.get('gate', '').lower()
        labels = gate_labels(gate)
        if not labels or labels - known or (labels & GATE_PHASES['release'] and not (labels <= GATE_PHASES['release'])):
            bad_gates.append(f"{row.get('purpose', '?')} ({row.get('gate', '').strip() or 'empty'})")
            continue
        if not (labels & GATE_PHASES[phase]):
            continue
        cell = row.get('command', '')
        code = INLINE_CODE.findall(cell)
        if re.match(r'(?i)\s*proposed\b', cell):
            kind, command = 'gap', None
        elif re.match(r'(?i)\s*(not applicable|n/a)\b', cell):
            kind, command = 'excluded', None
        elif len(code) > 1 and not PLACEHOLDER.search(cell):
            bad_commands.append(f"{row.get('purpose', '?')} ({len(code)} backticked commands; use separate rows or one compound command)")
            kind, command = 'gap', None
        elif code and not PLACEHOLDER.search(cell):
            cmd = code[0].strip('`').strip()
            outside = INLINE_CODE.sub('', cell).strip()
            if not cmd:
                bad_commands.append(f"{row.get('purpose', '?')} (empty command in backticks)")
                kind, command = 'gap', None
            elif outside:
                bad_commands.append(f"{row.get('purpose', '?')} (text outside backticks in Command cell; put only one command in backticks)")
                kind, command = 'gap', None
            else:
                kind, command = 'run', cmd
        else:
            kind, command = 'gap', None
        gates.append((row.get('purpose', '?'), gate, cell, command, kind))
    if header is None or 'gate' not in header:
        return [], 'the command inventory has no Gate column'
    problems = []
    if bad_gates:
        problems.append('unrecognized or mixed Gate label(s): ' + ', '.join(bad_gates)
                        + ' — use Development, Release, Documentation, Manual, or —')
    if bad_commands:
        problems.append('ambiguous Command cell(s): ' + '; '.join(bad_commands))
    if problems:
        return gates, '; '.join(problems)
    if phase == 'documentation' and not gates:
        return [], 'no command inventory row has Documentation in its Gate column'
    return gates, None


def run_gate_command(command, limit, env=None):
    proc = subprocess.Popen(
        command, shell=True, cwd=root, env=env,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
        start_new_session=(os.name == 'posix'),
    )
    try:
        stdout, stderr = proc.communicate(timeout=limit)
        return proc.returncode, stdout, stderr, False
    except subprocess.TimeoutExpired:
        if os.name == 'posix':
            try:
                os.killpg(proc.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
        else:
            proc.kill()
        try:
            proc.communicate(timeout=5)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait()
        return None, '', '', True


def non_documentation_changes():
    if not git('rev-parse', '--git-dir'):
        return None
    if git('rev-parse', '--verify', '--quiet', 'HEAD'):
        base = next((b for b in (git('merge-base', 'HEAD', ref) for ref in ('@{upstream}', 'origin/HEAD', 'main', 'master')) if b), 'HEAD')
        diff_files = git_z('diff', '--no-renames', '--name-only', '-z', base)
    else:
        staged = git_z('diff', '--cached', '--no-renames', '--name-only', '-z')
        unstaged = git_z('diff', '--no-renames', '--name-only', '-z')
        diff_files = None if (staged is None or unstaged is None) else (staged + unstaged)
    untracked = git_z('ls-files', '-z', '--others', '--exclude-standard')
    if diff_files is None or untracked is None:
        return None
    changed = set(diff_files) | set(untracked)
    return sorted(p for p in changed if p and Path(p).suffix.lower() not in PROSE_SUFFIXES and p not in GUIDANCE_RECORDS)


def dependency_files(limit=10):
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        r = Path(dirpath).relative_to(root)
        dirnames[:] = sorted(d for d in dirnames if not d.startswith('.') and d not in DEPENDENCY_SKIP and len(r.parts) < 3)
        found += sorted((r / f).as_posix() for f in filenames if DEPENDENCY_FILES.fullmatch(f))
    return found[:limit], len(found) > limit


def verify(phase, timeout, receipt, record):
    phase = 'documentation' if phase == 'docs' else phase
    # One "<phase> <project root>" entry per line; another project's verifier may still run.
    chain = [entry for entry in os.environ.get(VERIFY_CHAIN, '').split('\n') if entry] + [f'{phase} {root}']
    if chain[-1] in chain[:-1]:
        shown = ' -> '.join(entry.split(' ', 1)[0] for entry in chain)
        print(f'Refused: a gate command reran scripts/verify.py --verify {phase} inside itself ({shown}), '
              'which would repeat until memory runs out. Change that gate so it does not run the same phase.')
        sys.exit(2)
    gate_env = dict(os.environ, **{VERIFY_CHAIN: '\n'.join(chain)})
    gates, problem = inventory_gates(phase)
    commit = git('rev-parse', '--short', 'HEAD') or 'no commit'
    dirty = bool(git('status', '--porcelain'))
    results = []
    for purpose, gate, cell, command, kind in gates:
        entry = {'purpose': purpose, 'gate': gate, 'command': command, 'status': kind}
        if kind == 'gap':
            entry['detail'] = cell if cell and not PLACEHOLDER.search(cell) else 'not configured'
        elif kind == 'excluded':
            entry['detail'] = cell
        else:
            own = gate_timeout(gate)
            limit = own or timeout
            entry['timeout'] = limit
            started = time.monotonic()
            rc, stdout, stderr, timed_out = run_gate_command(command, limit, gate_env)
            if timed_out:
                source = "this gate's own limit" if own else 'the --timeout default; set a longer limit in its Gate cell, such as "timeout 60m"'
                entry['status'], entry['detail'] = 'failed', f'timed out after {limit}s ({source})'
                entry['output_tail'] = [entry['detail']]
            else:
                entry['status'] = 'passed' if rc == 0 else 'failed'
                entry['exit_code'] = rc
                entry['output_tail'] = (stdout + stderr).strip().splitlines()[-5:]
            entry['seconds'] = round(time.monotonic() - started, 1)
        results.append(entry)
    if phase == 'documentation':
        code = non_documentation_changes()
        if code is None:
            problem = problem or 'documentation mode needs git to check that only documentation changed'
        elif code:
            shown = ', '.join(code[:5]) + (f' and {len(code) - 5} more' if len(code) > 5 else '')
            results.append({'purpose': 'Change scope', 'gate': 'documentation', 'command': None, 'status': 'failed',
                            'detail': f'documentation mode is only for changes to documentation, and this work also changes {shown}. '
                                      'Run python3 scripts/verify.py --verify instead'})
    count = lambda s: sum(1 for e in results if e['status'] == s)
    failed, gaps = count('failed'), count('gap')
    state = 'failed' if failed else 'incomplete' if gaps or problem or not results else 'complete'
    def group(status):
        n = count(status)
        label = f"{n} {status}{'s' if status == 'gap' and n != 1 else ''}"
        names = [e['purpose'] for e in results if e['status'] == status]
        return f"{label}: {', '.join(names)}" if status in ('failed', 'gap') else label
    summary = '; '.join(group(s) for s in ('failed', 'passed', 'gap', 'excluded') if count(s)) or 'no gates ran'
    print(f'Verification: {state} ({phase} gates: {summary})')
    print(f"Candidate: {commit}{' with uncommitted changes' if dirty else ''}")
    if problem:
        print(f'  problem   {problem}')
    for e in results:
        detail = e.get('command') or e.get('detail', '')
        timing = f" ({e['seconds']}s)" if 'seconds' in e else ''
        print(f"  {e['status']:<9} {e['purpose']}: {detail}{timing}")
        if e['status'] == 'failed':
            for line in e.get('output_tail', []):
                print(f'            | {line}')
    if gaps:
        print(f'Gaps: {GAP_HINT}.')
    if any(e['status'] == 'gap' and re.search(r'(?i)dependenc', e['purpose']) for e in results):
        deps, more = dependency_files()
        if deps:
            print(f"Dependency files: {', '.join(deps)}{', and more' if more else ''}. Inspect them and report "
                  'pinned or outdated versions with published vulnerabilities; change none without review.')
    print('Report: quote the Verification line above verbatim as your verification status.')
    if receipt:
        Path(receipt).write_text(json.dumps({'state': state, 'phase': phase, 'commit': commit, 'uncommitted_changes': dirty,
                                             'date': date.today().isoformat(), 'problem': problem, 'gates': results}, indent=2) + '\n')
    sys.exit({'complete': 0, 'failed': 1}.get(state, 2))


def placeholders(record, exclusions=()):
    installed_md = {e['path'] if isinstance(e, dict) else e for e in record.get('files', [])
                    if (e['path'] if isinstance(e, dict) else e).endswith('.md')}
    counts = {}
    for rel_path in sorted(installed_md | ({'PROJECT_PROFILE.md'} if (root / 'PROJECT_PROFILE.md').is_file() else set())):
        if rel_path in COPY_TEMPLATES or (rel_path != 'PROJECT_PROFILE.md' and excluded(rel_path, exclusions)):
            continue
        path = root / rel_path
        if not path.is_file():
            continue
        text = path.read_text()
        if rel_path == 'PROJECT_PROFILE.md':
            before, _, after = text.partition(STAGE_MARKER)
            code, release = len(PLACEHOLDER.findall(prose(before))), len(PLACEHOLDER.findall(prose(after)))
        else:
            code, release = 0, len(PLACEHOLDER.findall(prose(text)))
        if code or release:
            counts[rel_path] = (code, release)
    return counts


def is_template_repo():
    manifest = root / 'PACKAGE_MANIFEST.json'
    if (root / '.guidance.json').is_file() or not ((root / 'MAINTAINING.md').is_file() and (root / 'manage.py').is_file() and manifest.is_file()):
        return False
    try:
        data = json.loads(manifest.read_text())
    except ValueError:
        return False
    return isinstance(data, dict) and data.get('package') == 'reusable-project-guidance' and 'repo_only' in data


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--verify', nargs='?', const='development', choices=['development', 'documentation', 'docs', 'release'],
                    help='run gate commands from PROJECT_PROFILE.md and print computed verification status')
    ap.add_argument('--timeout', type=int, default=900, help='seconds allowed per gate unless its Gate cell sets its own')
    ap.add_argument('--receipt', metavar='FILE', help='write --verify results as JSON')
    ap.add_argument('--require', choices=['code', 'release'], help='fail if placeholders remain at this stage')
    args = ap.parse_args()
    if is_template_repo():
        if args.verify:
            print('This is the unconfigured template repository; run python3 manage.py instead of scripts/verify.py --verify.')
            sys.exit(2)
        sys.exit(subprocess.run([sys.executable, str(root / 'manage.py')]).returncode)
    record, record_error = load_record()
    if args.verify:
        verify(args.verify, args.timeout, args.receipt, record or {})

    errors, notes = [], []
    if record_error:
        errors.append(record_error)
    record = record or {}
    files = walk()
    exclusions = recorded_exclusions(root / 'PROJECT_PROFILE.md')
    installed = record.get('files', [])
    installed_paths = [e['path'] if isinstance(e, dict) else e for e in installed]
    uninstalled = set(record.get('uninstalled', []))
    recorded = {p for p in installed_paths if excluded(p, exclusions) and not (root / p).is_file()}
    uninstalled |= recorded
    tools = set((record.get('installed') or record).get('tools') or ())

    linked_elsewhere = check_links(files, errors, uninstalled)
    check_shims(files, errors, not tools or 'claude' in tools)
    check_skills(record, errors)
    check_agents_tables(record, errors)
    check_budget(errors)
    check_guardrails(record, errors)

    for module, mod_files in record.get('module_files', {}).items():
        if mod_files and not any((root / p).is_file() for p in mod_files):
            errors.append(f"Installed configuration requires the {module} module, but none of its files are present; "
                          'reinstall it with manage.py --install from the agent-guidance checkout')
    modules = set((record.get('installed') or record).get('modules') or ())
    if 'enterprise' in modules:
        notes.extend(enterprise_notes())
    provenance = root / 'docs' / 'guidance-provenance.json'
    if provenance.is_file():
        try:
            json.loads(provenance.read_text())
        except ValueError as error:
            errors.append(f'docs/guidance-provenance.json: not valid JSON ({error})')
    absent = [p for p in installed_paths if not (root / p).is_file() and p not in uninstalled]
    if recorded:
        notes.append(f'{len(recorded)} packaged files absent as recorded in Excluded guidance.')
    if absent:
        notes.append(f'{len(absent)} packaged files absent and not recorded as excluded: ' + ', '.join(absent))
    if linked_elsewhere:
        notes.append(f'{linked_elsewhere} links point to uninstalled optional modules.')

    counts = placeholders(record, exclusions)
    code_total = sum(c for c, _ in counts.values())
    release_total = sum(r for _, r in counts.values())
    if args.require == 'code' and code_total:
        errors.append(f'{code_total} placeholders remain above "## Command inventory" in PROJECT_PROFILE.md')
    if args.require == 'release' and code_total + release_total:
        listed = ', '.join(f'{p} ({c + r})' for p, (c, r) in sorted(counts.items()))
        errors.append(f'{code_total + release_total} placeholders remain in {listed}; fill them or record exclusions before release')

    if errors:
        print('\n'.join(errors))
        print(f'FAIL (project mode): {len(errors)} problem(s).')
        sys.exit(1)
    present = sum(1 for p in installed_paths if (root / p).is_file())
    meta = record.get('installed') or record
    tier = meta.get('tier') or 'unspecified'
    print(f'PASS (project mode): {present} of {len(installed_paths)} packaged files present (tier {tier}); '
          'links, shims, skills and document budget consistent.')
    for line in notes:
        print(line)
    print(f'Placeholders: {code_total} before implementation, {release_total} before release.')


if __name__ == '__main__':
    main()
